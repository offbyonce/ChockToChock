"""Design audit: every style value in the interface, counted, with where it is used.

Run from the repository root: python3 tools/design-audit/audit.py . > docs/design/audit-tables.md
"""
import collections
import glob
import os
import re
import sys

ROOT = sys.argv[1]
files = sorted(
    glob.glob(f"{ROOT}/packages/ui/src/**/*.svelte", recursive=True)
    + glob.glob(f"{ROOT}/packages/ui/src/**/*.css", recursive=True)
    + glob.glob(f"{ROOT}/apps/web/src/**/*.svelte", recursive=True)
    + glob.glob(f"{ROOT}/apps/web/src/**/*.css", recursive=True)
)
files = [f for f in files if "/wasm/" not in f and "/generated/" not in f]


def styles(path):
    text = open(path).read()
    if path.endswith(".svelte"):
        return "\n".join(re.findall(r"<style[^>]*>(.*?)</style>", text, re.S))
    return text


DECL = re.compile(r"([a-z-]+)\s*:\s*([^;{}]+);")
RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")
LEN = re.compile(r"-?\d*\.?\d+(?:px|rem|em|vw|vh|%|ch)\b")
COLOR = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)|color-mix\([^;]*\)|var\(--[a-z-]+\)")

cat = collections.defaultdict(collections.Counter)
where = collections.defaultdict(lambda: collections.defaultdict(set))
classes = collections.defaultdict(set)


def add(kind, value, f):
    cat[kind][value] += 1
    where[kind][value].add(os.path.relpath(f, ROOT).replace("packages/ui/src/", ""))


SPACING = re.compile(r"^(padding|margin|gap|row-gap|column-gap|inset|top|left|right|bottom)(-|$)")
SIZE = re.compile(r"^(width|height|min-width|min-height|max-width|max-height|flex-basis)$")
COLOR_PROPS = re.compile(r"(color|background|fill|stroke|border|outline|box-shadow)")

for f in files:
    css = styles(f)
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for sel, body in RULE.findall(css):
        for c in re.findall(r"\.([a-zA-Z][\w-]*)", sel):
            classes[c].add(os.path.relpath(f, ROOT).replace("packages/ui/src/", ""))
        for prop, val in DECL.findall(body):
            val = val.strip()
            if SPACING.match(prop):
                for v in LEN.findall(val):
                    add("spacing", v, f)
            elif prop == "font-size":
                for v in LEN.findall(val) or [val]:
                    add("font-size", v, f)
            elif prop == "font-weight":
                add("font-weight", val, f)
            elif prop == "font":
                w = re.match(r"(\d{3}|bold|normal)\s", val)
                if w:
                    add("font-weight", w.group(1), f)
                for v in LEN.findall(val.split("/")[0]):
                    add("font-size", v, f)
                lh = re.search(r"/\s*([\d.]+)", val)
                if lh:
                    add("line-height", lh.group(1), f)
            elif prop == "line-height":
                add("line-height", val, f)
            elif prop == "letter-spacing":
                add("letter-spacing", val, f)
            elif prop.startswith("border-radius") or prop == "rx":
                add("radius", val, f)
            elif SIZE.match(prop):
                for v in LEN.findall(val):
                    add("size", f"{prop}: {v}", f)
            if prop.startswith("border") and not prop.startswith("border-radius") or prop == "outline":
                for v in re.findall(r"\d*\.?\d+px", val):
                    add("border-width", v, f)
            if prop == "box-shadow":
                add("shadow", val, f)
            if COLOR_PROPS.search(prop):
                for c in COLOR.findall(val):
                    add("color", c, f)
            if prop == "stroke-width":
                add("stroke-width (drawings)", val, f)

out = ["<!--", "SPDX-FileCopyrightText: 2026 offbyonce", "SPDX-License-Identifier: MIT", "-->", "# Design audit tables (generated by tools/design-audit/audit.py)", "", f"Files scanned: {len(files)}.", ""]
for kind in ["spacing", "font-size", "font-weight", "line-height", "letter-spacing", "radius", "border-width", "shadow", "color", "size", "stroke-width (drawings)"]:
    c = cat[kind]
    out.append(f"## {kind}: {len(c)} distinct values, {sum(c.values())} uses")
    out.append("")
    out.append("| value | uses | files |")
    out.append("| --- | ---: | --- |")
    for v, n in sorted(c.items(), key=lambda x: (-x[1], x[0])):
        fs = sorted(where[kind][v])
        out.append(f"| `{v}` | {n} | {', '.join(fs[:4])}{' +' + str(len(fs) - 4) if len(fs) > 4 else ''} |")
    out.append("")
dup = {c: fs for c, fs in classes.items() if len(fs) > 1}
out.append(f"## Class names styled in more than one file: {len(dup)}")
out.append("")
out.append("| class | files |")
out.append("| --- | --- |")
for c, fs in sorted(dup.items(), key=lambda x: (-len(x[1]), x[0])):
    out.append(f"| `.{c}` | {', '.join(sorted(fs))} |")
print("\n".join(out))
